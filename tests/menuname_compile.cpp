static uint32_t Rd32(const unsigned char* p) {
    return (uint32_t)p[0] | ((uint32_t)p[1] << 8) |
           ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
}

static const unsigned char* At(uint32_t va)
{
    if (va < CODE_BASE || va >= CODE_BASE + sizeof(ENGINE_CODE)) return nullptr;
    return ENGINE_CODE + (va - CODE_BASE);
}

// Walk one case handler. Returns false if it does not look like a handler at
// all; otherwise fills kind (always) and gf (-1 when the case makes no GF call).
static bool DecodeCase(uint32_t va, int& kind, int& gf)
{
    kind = -1;
    gf = -1;
    int pushed = -1;

    for (int step = 0; step < 12; step++) {
        const unsigned char* p = At(va);
        if (!p) return false;

        // 6A ib                     push imm8            (the GF index)
        if (p[0] == 0x6A) {
            pushed = p[1];
            va += 2;
            continue;
        }
        // 66 C7 05 disp32 iw        mov word ptr [disp32], imm16
        if (p[0] == 0x66 && p[1] == 0xC7 && p[2] == 0x05) {
            if (Rd32(p + 3) != KIND_ADDR) return false;
            kind = (int)((uint32_t)p[7] | ((uint32_t)p[8] << 8));
            va += 9;
            continue;
        }
        // E8 rel32                  call
        if (p[0] == 0xE8) {
            const uint32_t target = va + 5 + Rd32(p + 1);
            if (target == ENABLE_GF) gf = pushed;
            va += 5;
            continue;
        }
        // 83 C4 ib                  add esp, imm8
        if (p[0] == 0x83 && p[1] == 0xC4) { va += 3; continue; }
        // B8 id                     mov eax, imm32       (return value 3)
        if (p[0] == 0xB8) { va += 5; continue; }
        // C3                        ret
        if (p[0] == 0xC3) return kind >= 0;

        std::printf("FAIL  unrecognised opcode 0x%02X at 0x%08X\n", p[0], va);
        return false;
    }
    std::printf("FAIL  handler at 0x%08X did not reach a ret\n", va);
    return false;
}

int main()
{
    const int jtCount = (int)(sizeof(ENGINE_JT) / 4);

    // The engine's own bound: `cmp edx, 0x14 / ja default`, so 0x15 entries.
    if (jtCount != MENUNAME_PARAM_COUNT) {
        std::printf("FAIL  jump table has %d entries, model says %d\n",
                    jtCount, MENUNAME_PARAM_COUNT);
        g_failures++;
    }

    int gfSeen[16];
    std::memset(gfSeen, 0, sizeof(gfSeen));
    int transposed = 0;

    for (int param = 0; param < jtCount && param < MENUNAME_PARAM_COUNT; param++) {
        const uint32_t handler = Rd32(ENGINE_JT + param * 4);
        int kind = -1, gf = -1;
        if (!DecodeCase(handler, kind, gf)) {
            std::printf("FAIL  param %2d  handler 0x%08X did not decode\n", param, handler);
            g_failures++;
            continue;
        }

        Check(MenunameKind(param) == kind, "kind", param, MenunameKind(param), kind);
        Check(MenunameGfIndex(param) == gf, "gf index", param, MenunameGfIndex(param), gf);

        if (gf >= 0) {
            // Every GF case: kind is the GF index plus five, no exceptions.
            Check(kind == gf + 5, "kind==gf+5", param, kind, gf + 5);
            if (gf < 16) gfSeen[gf]++;
            // The transposition the model must not smooth over.
            if (param != gf + 3) transposed++;
        } else {
            // A non-GF case must not claim a GF name.
            Check(MenunameGfIndex(param) == -1, "non-GF", param, MenunameGfIndex(param), -1);
        }
    }

    // All sixteen GFs, exactly once each.
    for (int g = 0; g < 16; g++) {
        if (gfSeen[g] != 1) {
            std::printf("FAIL  GF %d appears %d times in the jump table, want 1\n", g, gfSeen[g]);
            g_failures++;
        }
    }

    // Two transposed pairs = four parameters out of place. If this ever reads
    // zero the fixture stopped being the engine's table.
    if (transposed != 4) {
        std::printf("FAIL  %d transposed jump-table entries, want 4 (params 8/9 and 14/15)\n",
                    transposed);
        g_failures++;
    }

    // Non-GF parameters: exactly five of them, which is exactly the number of
    // player-nameable non-GF names in FF8.
    int nonGf = 0, named = 0;
    for (int p = 0; p < MENUNAME_PARAM_COUNT; p++) {
        if (MenunameGfIndex(p) >= 0) {
            if (MenunameNameId(p) != 0) {
                std::printf("FAIL  param %2d is a GF but carries name id 0x%02X\n",
                            p, MenunameNameId(p));
                g_failures++;
            }
            continue;
        }
        nonGf++;
        if (MenunameNameId(p) != 0) named++;
    }
    if (nonGf != 5) {
        std::printf("FAIL  %d non-GF parameters, want 5 (Squall Rinoa Angelo Boko Griever)\n", nonGf);
        g_failures++;
    }
    // Squall/Rinoa/Angelo carry ids; Boko and Griever deliberately do not,
    // because which parameter is which is not settled.
    if (named != 3) {
        std::printf("FAIL  %d non-GF parameters carry a name id, want 3\n", named);
        g_failures++;
    }
    if (MenunameNameId(0) != 0x30) {
        std::printf("FAIL  param 0 name id 0x%02X, want 0x30 (Squall)\n", MenunameNameId(0));
        g_failures++;
    }

    // Out of range mirrors the engine's default: no kind, no GF, no name.
    if (MenunameKind(21) != -1 || MenunameGfIndex(21) != -1 || MenunameNameId(21) != 0 ||
        MenunameKind(-1) != -1 || MenunameGfIndex(-1) != -1 || MenunameNameId(-1) != 0) {
        std::printf("FAIL  out-of-range parameter did not fall back cleanly\n");
        g_failures++;
    }

    if (g_failures == 0)
        std::printf("menuname_compile: OK (%d parameters decoded from engine bytes)\n", jtCount);
    else
        std::printf("menuname_compile: %d FAILURE(S)\n", g_failures);
    return g_failures ? 1 : 0;
}
