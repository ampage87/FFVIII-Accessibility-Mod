// menuname_compile.cpp -- does the model of opcode_menuname match the engine?
//
// The fixture is NOT a transcription of the model. It is 480 bytes of FF8_EN.exe
// -- the twenty-one case handlers at 0x00521DD6..0x00521FB6 -- plus the 84-byte
// jump table at 0x00521FB8, copied out of the executable verbatim. The probe
// walks the real table, decodes the real instructions, and derives (kind, GF
// index) for every parameter from the machine code. Only then does it compare.
//
// This matters because the two things most likely to be wrong in the model are
// exactly the two things a hand-written fixture would copy from it: the
// transposed jump-table entries for params 8/9 and 14/15. Decoding the table
// catches a transposition; retyping it cannot.
//
// Build (host, no Windows headers):
//   g++ -std=c++17 -O0 -Isrc -o menuname_compile tests/menuname_compile.cpp && ./menuname_compile
//
// v0.38.1 (#98).

#include <cstdio>
#include <cstdint>
#include <cstring>

#include "field_menuname_model.inl"

using namespace FieldMenunameModel;

static int g_failures = 0;

static void Check(bool ok, const char* what, int param, int got, int want)
{
    if (ok) return;
    std::printf("FAIL  param %2d  %-12s got %d, engine says %d\n", param, what, got, want);
    g_failures++;
}

